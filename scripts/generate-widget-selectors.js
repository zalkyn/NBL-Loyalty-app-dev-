function blockOf(cls) {
    return cls.replace(/(__|--).*$/, "");
}

function labelFor(block) {
    if (AREA_LABELS[block]) return AREA_LABELS[block];
    const words = block.replace(/^nbl-/, "").split("-");
    return words.map((w, i) => (i === 0 ? w.charAt(0).toUpperCase() + w.slice(1) : w)).join(" ");
}

const css = readFileSync(CSS_PATH, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
const classes = [...new Set(css.match(/\.nbl-[a-z0-9_-]+/g) || [])]
    .map((c) => c.slice(1))
    .filter((c) => !EXCLUDED_CLASSES.has(c) && !EXCLUDED_BLOCKS.has(blockOf(c)));

const groups = new Map();
for (const cls of classes) {
    const label = labelFor(blockOf(cls));
    if (!groups.has(label)) groups.set(label, new Set());
    groups.get(label).add(`.${cls}`);
}

const out = [...groups.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([label, set]) => ({ label, selectors: [...set].sort() }));

const total = out.reduce((n, g) => n + g.selectors.length, 0);

writeFileSync(
    OUT_PATH,
    `// AUTO-GENERATED by scripts/generate-widget-selectors.js from ${CSS_PATH}.\n` +
    `// Do not edit by hand — run \`npm run widget:build\`.\n` +
    `// ${total} selectors in ${out.length} groups.\n\n` +
    `export const WIDGET_SELECTOR_GROUPS = ${JSON.stringify(out, null, 4)};\n`
);

console.log(`${OUT_PATH}: ${total} selectors in ${out.length} groups.`);
